/** Shared placeholder for screens whose real implementation lands in a later roadmap phase. */
@Composable
fun ComingSoonScreen(title: String, phaseNote: String, modifier: Modifier = Modifier) {
    Column(
        modifier = modifier.fillMaxSize().padding(24.dp),
        verticalArrangement = Arrangement.Center,
        horizontalAlignment = Alignment.CenterHorizontally,
    ) {
        Text(text = title, style = MaterialTheme.typography.headlineSmall, textAlign = TextAlign.Center)
        Text(text = phaseNote, style = MaterialTheme.typography.bodyMedium, textAlign = TextAlign.Center)
    }
}
